grant select, insert, delete on table public.requests to authenticated;
revoke all on table public.profiles from anon;
revoke all on table public.resources from anon;
revoke all on table public.requests from anon;

-- Create a profile as part of Auth signup, including when email confirmation
-- means the browser does not receive a session immediately.
create or replace function public.create_profile_for_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name, location)
  values (
    new.id,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
      nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
      'Neighbor'
    ),
    ''
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

revoke all on function public.create_profile_for_new_auth_user() from public, anon, authenticated;
drop trigger if exists create_profile_after_auth_signup on auth.users;
create trigger create_profile_after_auth_signup
  after insert on auth.users
  for each row execute function public.create_profile_for_new_auth_user();

-- Backfill profiles for accounts that existed before this trigger was added.
insert into public.profiles (id, name, location)
select
  u.id,
  coalesce(
    nullif(trim(u.raw_user_meta_data ->> 'name'), ''),
    nullif(split_part(coalesce(u.email, ''), '@', 1), ''),
    'Neighbor'
  ),
  ''
from auth.users as u
on conflict (id) do nothing;

