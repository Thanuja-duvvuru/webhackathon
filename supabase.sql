-- CommunityConnect Supabase setup for the existing tables:
-- profiles, resources, and requests.
-- Run in Supabase Dashboard -> SQL Editor. Safe to rerun.

-- These statements create a table only if it is missing; existing tables
-- created in the Table Editor are kept.
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null,
  location text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  owner_name text not null,
  resource_name text not null,
  category text not null,
  location text not null,
  description text not null,
  status text not null default 'Available'
    check (status in ('Available', 'Requested', 'Taken')),
  created_at timestamptz not null default now()
);

create table if not exists public.requests (
  id bigint generated by default as identity primary key,
  resource_id bigint not null references public.resources (id) on delete cascade,
  requester_id uuid not null references auth.users (id) on delete cascade,
  requester_name text,
  status text not null default 'Pending'
    check (status in ('Pending', 'Approved', 'Rejected', 'Cancelled')),
  created_at timestamptz not null default now()
);

-- Existing requests table was created without requester_name. Add it
-- without affecting existing request rows.
alter table public.requests
  add column if not exists requester_name text;

-- A returned request stays in request history, while its resource becomes
-- available to borrow again.
alter table public.requests
  drop constraint if exists requests_status_check;
alter table public.requests
  add constraint requests_status_check
  check (status in ('Pending', 'Approved', 'Rejected', 'Cancelled', 'Returned'));

create index if not exists resources_user_id_idx
  on public.resources (user_id);
create index if not exists resources_created_at_idx
  on public.resources (created_at desc);
create index if not exists requests_resource_id_idx
  on public.requests (resource_id);
create index if not exists requests_requester_id_idx
  on public.requests (requester_id);
create index if not exists requests_resource_id_created_at_idx
  on public.requests (resource_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.resources enable row level security;
alter table public.requests enable row level security;

-- Publish request status updates so a resource owner already using the app
-- receives an immediate in-app notification when a borrower returns an item.
do $$
begin
  if exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) and not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'requests'
  ) then
    execute 'alter publication supabase_realtime add table public.requests';
  end if;
end
$$;

