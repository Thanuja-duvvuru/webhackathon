-- Clean up policies from earlier names before applying policies to requests.
drop policy if exists "Users can view relevant resource requests" on public.requests;
drop policy if exists "Users can create their own resource requests" on public.requests;
drop policy if exists "Owners can update resource requests" on public.requests;
drop policy if exists "Requesters can cancel their requests" on public.requests;
drop policy if exists "Requesters can delete their own inactive requests" on public.requests;
drop policy if exists "Resource owners can read requests" on public.requests;
drop policy if exists "Users can request another user's available resource" on public.requests;
drop policy if exists "Resource owners can decide pending requests" on public.requests;
-- Requesters see their own requests; owners see requests for their resources.
create policy "Users can view relevant resource requests"
  on public.requests for select to authenticated
  using (
    requester_id = (select auth.uid())
    or exists (
      select 1 from public.resources r
      where r.id = requests.resource_id
        and r.user_id = (select auth.uid())
    )
  );

-- Requests must be for another user's currently available resource.
create policy "Users can create their own resource requests"
  on public.requests for insert to authenticated
  with check (
    requester_id = (select auth.uid())
    and exists (
      select 1 from public.resources r
      where r.id = requests.resource_id
        and r.user_id <> (select auth.uid())
        and r.status = 'Available'
    )
  );

-- The app only changes request status. Owners may approve/reject pending
-- requests; requesters may cancel their own pending requests.
revoke update on table public.requests from authenticated;
grant update (status) on table public.requests to authenticated;
create policy "Owners can update resource requests"
  on public.requests for update to authenticated
  using (
    status = 'Pending'
    and exists (
      select 1 from public.resources r
      where r.id = requests.resource_id
        and r.user_id = (select auth.uid())
    )
  )
  with check (
    status in ('Approved', 'Rejected')
    and exists (
      select 1 from public.resources r
      where r.id = requests.resource_id
        and r.user_id = (select auth.uid())
    )
  );
create policy "Requesters can cancel their requests"
  on public.requests for update to authenticated
  using (
    status = 'Pending'
    and requester_id = (select auth.uid())
  )
  with check (
    status = 'Cancelled'
    and requester_id = (select auth.uid())
  );
create policy "Requesters can delete their own inactive requests"
  on public.requests for delete to authenticated
  using (
    requester_id = (select auth.uid())
    and status in ('Pending', 'Rejected', 'Cancelled', 'Returned')
  );

-- Return a borrowed item in one transaction. The requester may only return
-- their own approved request; direct resource updates remain owner-only.
create or replace function public.return_requested_resource(request_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_resource_id bigint;
begin
  if auth.uid() is null then
    raise exception 'You must be signed in to return a resource.';
  end if;

  select r.resource_id
    into target_resource_id
  from public.requests as r
  where r.id = request_id
    and r.requester_id = auth.uid()
    and r.status = 'Approved'
  for update;

  if target_resource_id is null then
    raise exception 'This approved request was not found or has already been returned.';
  end if;

  update public.requests
  set status = 'Returned'
  where id = request_id;

  update public.resources
  set status = 'Available'
  where id = target_resource_id;

  if not found then
    raise exception 'The requested resource no longer exists.';
  end if;
end;
$$;

revoke all on function public.return_requested_resource(bigint) from public, anon;
grant execute on function public.return_requested_resource(bigint) to authenticated;

